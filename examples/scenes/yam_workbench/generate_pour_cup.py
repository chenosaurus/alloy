"""Generate the glass mug with a loop handle and its rigid collision hulls."""
from pathlib import Path

import numpy as np
from scipy.spatial import ConvexHull

from alloy.importers.common.objio import hulls_obj_text, mesh_obj_text, read_hulls_obj, sha256_bytes
from .glassware import DEPTH, RADIUS, WALL, cup_mesh


def convex_part(points):
    hull = ConvexHull(points)
    triangles = hull.simplices.copy()
    for triangle, plane in zip(triangles, hull.equations):
        a, b, c = points[triangle]
        if np.dot(np.cross(b - a, c - a), plane[:3]) < 0:
            triangle[1], triangle[2] = triangle[2], triangle[1]
    return points, triangles


def main():
    assets = Path(__file__).with_name("assets")
    segments = 96
    vertices, faces = cup_mesh(segments)
    vertices = vertices.tolist()
    # Leave two openings on the outside of the cup for the handle's attachments.
    lower, upper, half_depth = .028, .090, .008
    first, last = 3 * segments // 4 - 4, 3 * segments // 4 + 4
    wall_rings = [0]
    for z in (lower - half_depth, lower + half_depth, upper - half_depth, upper + half_depth):
        wall_rings.append(len(vertices))
        vertices.extend((x, y, z) for x, y, _ in vertices[:segments])
    wall_rings.append(segments)
    faces = faces[2 * segments:].tolist()  # replace only the outer wall

    def quad(a, b, c, d):
        faces.extend(((a, b, c), (a, c, d)))

    for band, (bottom, top) in enumerate(zip(wall_rings, wall_rings[1:])):
        for i in range(segments):
            if band in (1, 3) and first <= i < last:
                continue
            j = (i + 1) % segments
            quad(bottom + i, bottom + j, top + j, top + i)

    def perimeter(bottom, top):
        return (list(range(bottom + first, bottom + last + 1))
                + list(range(top + last, top + first - 1, -1)))

    x_coords = [vertices[i][0] for i in range(first, last + 1)]

    def section(y, z, inward_y, inward_z):
        start = len(vertices)
        for sign, xs in ((1, x_coords), (-1, reversed(x_coords))):
            vertices.extend((x, y + sign * half_depth * inward_y, z + sign * half_depth * inward_z) for x in xs)
        return list(range(start, len(vertices)))

    # Sweep through two rounded corners and a straight outer grip. The section's
    # inward edge starts below the top attachment and ends above the bottom one.
    grip_y, bend = -.081, .012
    arc = np.linspace(0, np.pi / 2, 7)
    top_bend = [section(grip_y + bend * (1 - np.sin(t)), upper - bend * (1 - np.cos(t)),
                        np.sin(t), -np.cos(t)) for t in arc]
    bottom_bend = [section(grip_y + bend * (1 - np.cos(t)), lower + bend * (1 - np.sin(t)),
                           np.cos(t), np.sin(t)) for t in arc]
    top_port = perimeter(wall_rings[3], wall_rings[4])
    bottom_port = perimeter(wall_rings[2], wall_rings[1])
    sections = [top_port, *top_bend, *bottom_bend, bottom_port]
    for start, end in zip(sections, sections[1:]):
        for i in range(len(start)):
            j = (i + 1) % len(start)
            quad(start[i], start[j], end[j], end[i])

    # Keep the handle hole clear in rigid contacts as well as on the particle surface.
    _, hulls = read_hulls_obj(assets / "glass-cup.hulls.obj")
    for piece in ([top_port, top_bend[0]], top_bend[:4], top_bend[3:],
                  [top_bend[-1], bottom_bend[0]], bottom_bend[:4], bottom_bend[3:],
                  [bottom_bend[-1], bottom_port]):
        points = np.asarray([vertices[i] for ring in piece for i in ring])
        hulls.append(convex_part(points))
    mesh = mesh_obj_text(np.asarray(vertices), np.asarray(faces), header="Generated by generate_pour_cup.py")
    (assets / "pour-cup.obj").write_bytes(mesh.encode())
    (assets / "pour-cup.hulls.obj").write_text(hulls_obj_text(hulls, sha256_bytes(mesh.encode())))


if __name__ == "__main__":
    main()
