"""Generate the glass beaker and its open-cavity collision hulls."""
from pathlib import Path

import numpy as np

from alloy.importers.common.objio import hulls_obj_text, mesh_obj_text, read_hulls_obj, sha256_bytes
from .generate_pour_cup import convex_part
from .glassware import DEPTH, WALL, cup_mesh


def beaker_vertices(vertices):
    vertices = vertices * .75
    rim = np.isclose(vertices[:, 2], .75 * (DEPTH + WALL))
    angles = np.arctan2(vertices[rim, 1], vertices[rim, 0])
    # Flare a narrow section of the rim into a pouring spout.
    vertices[rim, 0] += .012 * np.clip(1 - np.abs(angles) / .45, 0, 1) ** 2
    return vertices


def main():
    assets = Path(__file__).with_name("assets")
    vertices, faces = cup_mesh()
    _, cup_hulls = read_hulls_obj(assets / "glass-cup.hulls.obj")
    hulls = [convex_part(beaker_vertices(points)) for points, _ in cup_hulls]
    mesh = mesh_obj_text(beaker_vertices(vertices), faces, header="Generated by generate_beaker.py")
    (assets / "glass-beaker.obj").write_bytes(mesh.encode())
    (assets / "glass-beaker.hulls.obj").write_text(hulls_obj_text(hulls, sha256_bytes(mesh.encode())))


if __name__ == "__main__":
    main()
