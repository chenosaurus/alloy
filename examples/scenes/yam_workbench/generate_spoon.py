"""Generate the workbench's dished spoon and its collision hulls."""
import numpy as np
from scipy.interpolate import PchipInterpolator

from alloy.importers.common.objio import hulls_obj_text, mesh_obj_text, sha256_bytes
from alloy.workbench.glassware import ASSETS

from .generate_pour_cup import convex_part

# Lengthwise cross sections in metres: x, half width, centre height, bowl rise, half thickness.
PROFILE = np.array([
    (-.035, 0., .012, 0., 0.),
    (-.032, .010, .009, .003, .0015),
    (-.026, .017, .0055, .006, .0015),
    (-.017, .021, .0025, .009, .0015),
    (-.005, .022, .0015, .010, .0015),
    (.008, .021, .0025, .0095, .0015),
    (.021, .0175, .005, .007, .0015),
    (.033, .010, .009, .003, .0015),
    (.042, .0055, .013, 0., .002),
    (.052, .0065, .017, 0., .0035),
    (.064, .008, .023, 0., .0045),
    (.083, .0095, .027, 0., .0055),
    (.104, .010, .026, 0., .0055),
    (.123, .010, .018, 0., .0055),
    (.139, .0095, .009, 0., .005),
    (.145, .0075, .005, 0., .005),
    (.149, .004, .005, 0., .0035),
    (.151, 0., .005, 0., 0.),
])


def main():
    assets = ASSETS
    stations = PROFILE[:, 0]
    subdivisions = 4
    xs = np.concatenate([np.linspace(a, b, subdivisions, endpoint=False) for a, b in zip(stations, stations[1:])])
    interpolate = PchipInterpolator(stations, PROFILE[:, 1:], axis=0)
    angles = np.linspace(0, 2 * np.pi, 32, endpoint=False)
    cosine, sine = np.cos(angles), np.sin(angles)
    vertices = [(stations[0], 0., PROFILE[0, 2])]
    for x, (width, height, rise, thickness) in zip(xs[1:], interpolate(xs[1:])):
        # Rounded rectangle in the handle; elliptical sections keep the spoon rim thin.
        blend = np.clip((x - .042) / .022, 0., 1.)
        exponent = 1. - .45 * blend
        y = width * np.sign(cosine) * np.abs(cosine) ** exponent
        z = height + rise * cosine ** 2 + thickness * np.sign(sine) * np.abs(sine) ** exponent
        vertices.extend(zip(np.full(len(angles), x), y, z))
    vertices.append((stations[-1], 0., PROFILE[-1, 2]))
    vertices = np.asarray(vertices)

    faces = []
    count = len(angles)
    rings = len(xs) - 1
    last_ring = 1 + (rings - 1) * count
    for i in range(count):
        j = (i + 1) % count
        faces.extend(((0, 1 + j, 1 + i), (len(vertices) - 1, last_ring + i, last_ring + j)))
    for ring in range(rings - 1):
        for i in range(count):
            j = (i + 1) % count
            a, b = 1 + ring * count + i, 1 + ring * count + j
            faces.extend(((a, b, b + count), (a, b + count, a + count)))

    # Follow the handle arch with separate convex parts, leaving room below the grip.
    cuts = (stations[0], .008, .042, .064, .083, .104, .123, .139, stations[-1])
    sections = vertices[1:-1].reshape(rings, count, 3)
    coarse_sections = sections[subdivisions - 1::subdivisions, ::4]
    collision = np.vstack((vertices[0], coarse_sections.reshape(-1, 3), vertices[-1]))
    length = collision[:, 0]
    hulls = []
    for lo, hi in zip(cuts, cuts[1:]):
        points, triangles = convex_part(collision[(length >= lo) & (length <= hi)])
        used, indices = np.unique(triangles, return_inverse=True)
        hulls.append((points[used], indices.reshape(triangles.shape)))
    mesh = mesh_obj_text(vertices, np.asarray(faces), header="Generated by generate_spoon.py")
    (assets / "steel-spoon.obj").write_bytes(mesh.encode())
    (assets / "steel-spoon.hulls.obj").write_text(hulls_obj_text(hulls, sha256_bytes(mesh.encode())))


if __name__ == "__main__":
    main()
